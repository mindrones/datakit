import * as _ from 'lamb';

/**
 * Return a string joining the provided array items with a colon
 * @see {@link https://ascartabelli.github.io/lamb/module-lamb.html#joinWith|joinWith}
 *
 * @example
 * > joinWithColon(['a', 'b', 'c'])
 * 'a:b:c'
 *
 * @since 0.1.0
 */
export const joinWithColon = _.joinWith(':');
